/* Keep the library and flashcards available without downloading every subtitle file. */
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const root = path.resolve(__dirname, '..');
const films = [
  ['hans', 'HANS', 'hans'],
  ['trudes-fahrstuhl', 'TRUDES_FAHRSTUHL', 'trudes_fahrstuhl'],
  ['erdmaennchen-nudeltrick', 'ERDMAENNCHEN_NUDELTRICK', 'erdmaennchen_nudeltrick'],
  ['erdmaennchen-schmucklose', 'ERDMAENNCHEN_SCHMUCKLOSE', 'erdmaennchen_schmucklose'],
  ['pinguine-popcorn-panik', 'PINGUINE_POPCORN_PANIK', 'pinguine_popcorn_panik'],
  ['courage-diamantraub', 'COURAGE_DIAMANTRAUB', 'courage_diamantraub'],
  ['spongebob-pizza', 'SPONGEBOB_PIZZA', 'spongebob_pizza'],
  ['we-bare-bears-mall', 'WE_BARE_BEARS_MALL', 'we_bare_bears_mall'],
  ['frieren-s01e01', 'FRIEREN_S01E01', 'frieren_s01e01'],
  ['sakura-s01e01', 'SAKURA_S01E01', 'sakura_s01e01']
];
const context = vm.createContext({});
let output = '/* Generated by scripts/build-kino-metadata.cjs from the reviewed lessons. */\n';
for (const [stem, symbol, key] of films) {
  for (const suffix of ['aligned', 'lesson']) vm.runInContext(fs.readFileSync(path.join(root, `${stem}-${suffix}.js`), 'utf8'), context);
  const data = JSON.parse(vm.runInContext(`JSON.stringify(${symbol}_LESSON)`, context));
  delete data.chapterData.captionCues;
  output += `const ${symbol}_LESSON = ${JSON.stringify(data)};\n`;
  output += `Object.defineProperty(${symbol}_LESSON.chapterData, 'captionCues', { get: () => KinoData.captions('${key}') });\n`;
}
fs.writeFileSync(path.join(root, 'kino-metadata.js'), output);
console.log(`Kino metadata: ${Buffer.byteLength(output)} bytes; reviewed flashcards retained.`);
