"""Create seek-friendly viewing copies; never re-encode audio or overwrite originals."""
from pathlib import Path
import json
import subprocess

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'video/kino-light'
QA = ROOT / 'qa/kino-light'
MOVIES = {
    'peppa_supermarkt': 'Peppa_Wutz_Supermarkt.mp4',
    'pizzaschwester': 'pizzaschwester.mp4',
    'babysitter': 'babysitter.mp4',
    'hans': 'hans.mp4',
    'trudes_fahrstuhl': 'trudes_fahrstuhl.mp4',
    'erdmaennchen_nudeltrick': 'erdmaennchen_nudeltrick.mp4',
    'frieren_s01e01': 'frieren_s01e01.mp4',
    'sakura_s01e01': 'sakura_s01e01.mp4',
}


def probe(path):
    return json.loads(subprocess.check_output([
        'ffprobe', '-v', 'error', '-show_streams', '-show_format', '-of', 'json', str(path)
    ], text=True))


def audio_hash(path):
    return subprocess.check_output([
        'ffmpeg', '-v', 'error', '-i', str(path), '-map', '0:a:0',
        '-c', 'copy', '-f', 'streamhash', '-hash', 'sha256', '-'
    ], text=True).strip()


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    QA.mkdir(parents=True, exist_ok=True)
    manifest_path = ROOT / 'kino-media-manifest.js'
    # Other reviewed film pipelines also register viewing copies here.
    manifest = json.loads(manifest_path.read_text(encoding='utf8').split('const KINO_MEDIA_MANIFEST = ', 1)[1].strip().removesuffix(';')) if manifest_path.exists() else {}
    evidence = []
    for key, name in MOVIES.items():
        source = ROOT / 'video' / name
        target = OUT / f'{key}-480p-v2.mp4'
        original = probe(source)
        stream = next(s for s in original['streams'] if s['codec_type'] == 'video')
        num, den = map(int, stream['avg_frame_rate'].split('/'))
        fps = max(1, round(num / den))
        if not target.exists():
            temporary = target.with_suffix('.partial.mp4')
            print(f'Encoding {key} (original audio copied)', flush=True)
            subprocess.run([
                'ffmpeg', '-hide_banner', '-loglevel', 'error', '-y', '-i', str(source),
                '-map', '0:v:0', '-map', '0:a:0',
                '-vf', 'scale=-2:min(480\\,ih)', '-c:v', 'libx264',
                '-preset', 'veryfast', '-crf', '25', '-maxrate', '900k', '-bufsize', '1800k',
                '-threads', '3', '-pix_fmt', 'yuv420p', '-g', str(fps),
                '-keyint_min', str(fps), '-sc_threshold', '0',
                '-force_key_frames', 'expr:gte(t,n_forced*1)',
                '-c:a', 'copy', '-movflags', '+faststart', str(temporary)
            ], check=True)
            temporary.replace(target)
        optimized = probe(target)
        assert audio_hash(source) == audio_hash(target), f'Audio changed: {key}'
        assert abs(float(original['format']['duration']) - float(optimized['format']['duration'])) < .05
        keyframes = json.loads(subprocess.check_output([
            'ffprobe', '-v', 'error', '-skip_frame', 'nokey', '-select_streams', 'v:0',
            '-show_entries', 'frame=best_effort_timestamp_time', '-of', 'json', str(target)
        ], text=True))['frames']
        times = [float(f['best_effort_timestamp_time']) for f in keyframes]
        max_gap = max(b - a for a, b in zip(times, times[1:]))
        assert max_gap <= 1.05, f'Keyframes too far apart: {key}: {max_gap}'
        row = dict(key=key, source=str(source.relative_to(ROOT)).replace('\\', '/'),
                   src=str(target.relative_to(ROOT)).replace('\\', '/'),
                   originalBytes=source.stat().st_size, lightBytes=target.stat().st_size,
                   reductionPercent=round(100 * (1 - target.stat().st_size / source.stat().st_size), 2),
                   audioBitstreamUnchanged=True, maxKeyframeGapSeconds=round(max_gap, 6),
                   durationSeconds=float(optimized['format']['duration']))
        assert row['lightBytes'] < row['originalBytes'], f'Viewing copy is larger: {key}'
        evidence.append(row)
        manifest[key] = {'src': row['src'], 'label': 'Tiết kiệm 480p'}
        (QA / 'encodes.json').write_text(json.dumps(evidence, ensure_ascii=False, indent=2), encoding='utf-8')
        print(json.dumps(row, ensure_ascii=False), flush=True)
    (ROOT / 'kino-media-manifest.js').write_text(
        '/* Generated by scripts/build-kino-light.py. Audio is copied bit for bit. */\n'
        'const KINO_MEDIA_MANIFEST = ' + json.dumps(manifest, ensure_ascii=False, indent=2) + ';\n', encoding='utf-8')


if __name__ == '__main__':
    main()
