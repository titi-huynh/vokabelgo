const { chromium } = require('@playwright/test');
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');

(async () => {
  const browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
  const out = path.join(__dirname, 'screenshots');
  fs.mkdirSync(out, { recursive: true });
  const url = 'http://127.0.0.1:3000/design/teach-me-v01/demo/index.html';
  const click = (a, suffix = '') => page.locator(`[data-action="${a}"]${suffix}`).first().click();
  const getState = () => page.evaluate(() => JSON.parse(localStorage.getItem('may_teachme_demo_v1')));
  const send = async text => { await page.locator('#answer').fill(text); await page.locator('#send-answer').click(); };
  const reset = async () => { await page.evaluate(() => localStorage.removeItem('may_teachme_demo_v1')); await page.goto(url); };
  const start = async id => { await click('source', `[data-task="${id}"]`); await click('start'); };
  const has = async text => assert.ok((await page.locator('main').innerText()).includes(text), text);
  const noOverflow = async () => assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'No horizontal overflow');
  const report = msg => process.stdout.write('PASS ' + msg + '\n');
  try {
    await page.goto(url);
    await has('Hôm nay, bạn kể');
    await noOverflow();
    await page.screenshot({ path: path.join(out, '01-home-desktop.png'), fullPage: true });
    report('Homepage, both task cards, assets and desktop layout');

    await page.evaluate(() => localStorage.setItem('vokabelgo_srs_state_v1', '{"sentinel":"unchanged"}'));
    await start('weil');
    await send('Weil nêu lý do. Động từ chia đứng cuối mệnh đề phụ.');
    assert.equal((await getState()).session.feedback.verdict, 'met');
    await click('next');
    await send('Ich bleibe heute zu Hause, weil es draußen kalt ist.');
    assert.equal((await getState()).session.feedback.verdict, 'met');
    await click('next');
    let s = await getState();
    assert.equal(s.history.length, 1);
    assert.ok(s.history[0].results.every(r => r.verdict === 'met' && r.supports.length === 0));
    assert.ok(s.queue.weil.dueAt);
    assert.equal(await page.evaluate(() => localStorage.getItem('vokabelgo_srs_state_v1')), '{"sentinel":"unchanged"}');
    await page.reload();
    assert.equal((await getState()).history.length, 1);
    await page.screenshot({ path: path.join(out, '02-summary-desktop.png'), fullPage: true });
    report('Grammar happy path accepts alternate wording, saves once, preserves vocabulary SRS');

    await click('review');
    await send('Ich gehe früh ins Bett, weil ich müde bin.');
    await click('next');
    s = await getState();
    assert.equal(s.history.length, 2);
    assert.equal(s.history[1].mode, 'review');
    assert.equal(s.history[1].results.length, 1);
    assert.equal(Object.keys(s.queue).length, 1);
    report('Novel review scenario and deduplicated review queue');

    await reset();
    await start('weil');
    await page.locator('#answer').fill('Bản nháp của em');
    await click('hint');
    await click('pause');
    await page.reload();
    await has('Zehn giữ trang này cho bạn rồi.');
    await click('resume');
    assert.equal(await page.locator('#answer').inputValue(), 'Bản nháp của em');
    assert.ok((await getState()).session.supports[0].includes('keywords'));
    await click('source-modal');
    assert.ok((await getState()).session.supports[0].includes('source'));
    await click('translation');
    assert.ok(await page.locator('dialog .translation').isVisible());
    await click('close');
    await send('Weil nêu lý do. Động từ chia đứng cuối.');
    await click('next');
    await send('Ich bleibe zu Hause, weil es ist kalt.');
    await has('đổi vị trí của ist');
    assert.ok(!(await page.locator('.feedback').innerText()).includes('đứng cuối'));
    const repairQuestion = (await getState()).session.feedback.followUp;
    await click('report');
    await click('save-report');
    assert.equal((await getState()).reports.length, 1);
    await click('retry');
    assert.equal(await page.locator('.prompt').innerText(), repairQuestion);
    await send('Ich bleibe zu Hause, weil es kalt ist.');
    await click('next');
    s = await getState();
    assert.ok(s.history[0].results[1].supports.includes('inherited'));
    assert.ok(s.history[0].results[1].supports.includes('followup'));
    await has('Làm được sau hỗ trợ');
    report('Draft, hints, source view survive pause/reload; error → retry → assisted result; local report');

    await reset();
    await start('weil');
    await send('Động từ chia đứng cuối.');
    await click('retry');
    await send('Động từ chia đứng cuối.');
    await has('Một cách nói để tham khảo');
    assert.equal(await page.locator('[data-action="retry"]').count(), 0);
    await click('next');
    await send('Ich bleibe zu Hause, weil es ist kalt.');
    await click('retry');
    await send('Ich bleibe zu Hause, weil es ist kalt.');
    await click('next');
    s = await getState();
    assert.equal(s.session.attempts.flat().length, 4);
    assert.ok(s.history[0].results.some(r => r.verdict === 'not_yet'));
    report('Two attempts per step, model fallback and completion without false success');

    await reset();
    await start('weil');
    await send('Một câu nằm ngoài phạm vi.');
    await has('Giới hạn bản thử');
    await click('accept-model');
    assert.equal((await getState()).session.attempts[0].length, 1);
    await click('next');
    await send('Eine andere Antwort.');
    await click('accept-model');
    await click('next');
    s = await getState();
    assert.ok(s.history[0].results.every(r => r.verdict === 'unknown'));
    assert.equal(Object.keys(s.queue).length, 0);
    report('Unknown answers are not marked wrong; viewing model does not invent attempts or review dates');

    await reset();
    await start('lena');
    await send('Hai bạn cùng đi mua đồ và nấu súp.');
    await click('next');
    await send('Weil sie mit Mia einen Film sehen möchte.');
    await click('next');
    s = await getState();
    assert.ok(s.history[0].results.every(r => r.verdict === 'met'));
    await click('journal');
    await click('history');
    assert.ok(await page.locator('dialog').isVisible());
    await click('close');
    report('Reading comprehension in Vietnamese and German, journal and result detail');

    await reset();
    await start('weil');
    assert.equal((await page.locator('.prompt').innerText()).split('?').length - 1, 1);
    await send('Weil là vì, để nói lý do.');
    assert.equal((await getState()).session.feedback.verdict, 'met');
    await click('next');
    await page.locator('.conversation-memory summary').click();
    await has('Weil là vì, để nói lý do.');
    await has('Vậy là weil giúp mình nói lý do.');
    report('One question at a time; meaning alone satisfies the meaning task; conversational bridge retains prior exchange');

    await reset();
    await start('lena');
    await send('Hai bạn cùng nấu súp.');
    assert.equal((await getState()).session.feedback.verdict, 'partial');
    assert.ok((await page.locator('.feedback').innerText()).includes('nấu súp'));
    assert.ok(!(await page.locator('.feedback').innerText()).includes('xem phim'));
    const readingFollowUp = (await getState()).session.feedback.followUp;
    await click('retry');
    assert.equal(await page.locator('.prompt').innerText(), readingFollowUp);
    await send('Xem phim.');
    assert.equal((await getState()).session.feedback.verdict, 'met');
    assert.equal((await getState()).session.feedback.evidenceQuotes.length, 2);
    report('Focused follow-up accepts only the missing activity and retains evidence from both turns');


    await reset();
    await page.setViewportSize({ width: 390, height: 844 });
    await noOverflow();
    await page.screenshot({ path: path.join(out, '03-home-mobile.png'), fullPage: true });
    await start('lena');
    await page.locator('.examples summary').click();
    await click('sample', '[data-index="0"]');
    await page.locator('#send-answer').click();
    assert.ok((await getState()).session.supports[0].includes('sample'));
    await click('next');
    await click('hint');
    await noOverflow();
    await page.screenshot({ path: path.join(out, '04-session-mobile.png'), fullPage: true });
    await click('skip');
    await click('next');
    await noOverflow();
    s = await getState();
    assert.equal(s.history[0].results[1].verdict, 'skipped');
    assert.equal(s.queue.lena.status, 'pending');
    await click('reset-dialog');
    await click('reset');
    assert.equal((await getState()).history.length, 0);
    report('Mobile layout, sample-as-support, skip and scoped reset');

    await page.setViewportSize({ width: 1440, height: 1000 });
    await start('weil');
    await page.locator('#answer').fill('Weil nêu lý do. Động từ chia đứng cuối.');
    await noOverflow();
    await page.screenshot({ path: path.join(out, '05-session-desktop.png'), fullPage: true });
    await page.evaluate(() => { Storage.prototype.setItem = function(){throw new Error('storage blocked');}; });
    await send('Weil nêu lý do. Động từ chia đứng cuối.');
    await click('next');
    await send('Ich bleibe zu Hause, weil es kalt ist.');
    await click('next');
    await has('Chưa lưu được trên trình duyệt.');
    report('Storage failure does not claim saved');

    assert.deepEqual(errors, []);
    report('No browser console errors or runtime exceptions');
    process.stdout.write('Screenshots: ' + out + '\n');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
